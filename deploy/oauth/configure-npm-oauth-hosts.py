#!/usr/bin/env python3
"""Configure the NPM proxy hosts of OCR-AM-13 on the TrueNAS host (run as root there).

ocr-auth.andre.goiania.br -> Keycloak ClusterIP, only the OIDC/login paths of realm "ocr"
(plus RFC 8414 path-insert discovery aliases); admin, master realm, account console and
dynamic client registration answer 404.
ocr-mcp.andre.goiania.br -> the OCR NodePort, only /mcp, protected-resource metadata and
/api/v1 (the application applies its own allowlist), with the gateway secret header that
lets the OCR treat these requests as arriving over the HTTPS tunnel.

The secret is read from a private file and written only to NPM's private data volume.
The SQLite database is backed up first; nginx -t runs before reload.
"""
import json
import os
from pathlib import Path
import shutil
import sqlite3
import subprocess
from datetime import datetime

DB = Path("/mnt/NVME/docker/volumes/nginx-proxy-manager/data/database.sqlite")
NGINX_DIR = Path("/mnt/NVME/docker/volumes/nginx-proxy-manager/data/nginx/proxy_host")
GATEWAY = Path(os.environ.get("OCR_GATEWAY_SECRET_FILE", "/mnt/NVME/ocr-oauth/secrets/gateway_secret"))
AUTH, MCP = "ocr-auth.andre.goiania.br", "ocr-mcp.andre.goiania.br"
OCR_UPSTREAM = ("192.168.3.140", 31800)
REALM = "ocr"


def keycloak_upstream():
    ip = subprocess.check_output(["k3s", "kubectl", "-n", "ocr-oauth", "get", "svc", "keycloak",
                                  "-o", "jsonpath={.spec.clusterIP}"], text=True).strip()
    return ip, 8080


def headers(extra=""):
    return f"""    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-Proto https;
    proxy_set_header X-Forwarded-Host $host;
    proxy_set_header X-Forwarded-Port 443;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_http_version 1.1;
{extra}"""


def auth_locations(host, port):
    base = f"http://{host}:{port}"
    keycloak_buffers = "    proxy_buffer_size 128k;\n    proxy_buffers 4 256k;\n    proxy_busy_buffers_size 256k;\n"
    return f"""location = /.well-known/oauth-authorization-server/realms/{REALM} {{
    proxy_pass {base}/realms/{REALM}/.well-known/oauth-authorization-server;
{headers()}  }}
  location = /.well-known/openid-configuration/realms/{REALM} {{
    proxy_pass {base}/realms/{REALM}/.well-known/openid-configuration;
{headers()}  }}
  location ^~ /resources/ {{
    proxy_pass {base};
{headers()}  }}
  location ~ ^/realms/{REALM}/(\\.well-known/(openid-configuration|oauth-authorization-server)|protocol/openid-connect/(auth|token|token/introspect|certs|revoke|logout|userinfo|login-status-iframe\\.html(/init)?|3p-cookies/.*)|login-actions/.*)$ {{
    proxy_pass {base};
{headers(keycloak_buffers)}  }}
  location / {{
    return 404;
  }}
"""


def mcp_locations(host, port, secret):
    return f"""location ~ ^/(mcp|\\.well-known/oauth-protected-resource(/mcp)?|api/v1/.*)$ {{
    proxy_pass http://{host}:{port};
{headers()}    proxy_set_header X-OCR-Gateway "{secret}";
    proxy_buffering off;
    proxy_read_timeout 300s;
    client_max_body_size 64m;
  }}
  location / {{
    return 404;
  }}
"""


def conf(host_id, domain, upstream, locations):
    return f"""# ------------------------------------------------------------
# {domain} (OCR-AM-13; generated by deploy/oauth/configure-npm-oauth-hosts.py)
# ------------------------------------------------------------

server {{
  set $forward_scheme http;
  set $server         "{upstream[0]}";
  set $port           {upstream[1]};

  listen 80;
  listen [::]:80;

  server_name {domain};
  http2 off;

  include conf.d/include/block-exploits.conf;

  access_log /data/logs/proxy-host-{host_id}_access.log proxy;
  error_log /data/logs/proxy-host-{host_id}_error.log warn;

  if ($http_x_forwarded_proto = "http") {{ return 301 https://$host$request_uri; }}

  {locations}
  include /data/nginx/custom/server_proxy[.]conf;
}}
"""


def upsert(conn, domain, upstream, advanced):
    meta = '{"nginx_online":true,"nginx_err":null}'
    for row in conn.execute("select id, domain_names from proxy_host where is_deleted=0"):
        if domain in json.loads(row[1] or "[]"):
            conn.execute("update proxy_host set modified_on=datetime('now'), forward_scheme='http', forward_host=?,"
                         " forward_port=?, block_exploits=1, allow_websocket_upgrade=0, enabled=1, advanced_config=?,"
                         " meta=? where id=?", (upstream[0], upstream[1], advanced, meta, row[0]))
            return row[0]
    cursor = conn.execute(
        """insert into proxy_host (created_on, modified_on, owner_user_id, is_deleted, domain_names, forward_host,
           forward_port, access_list_id, certificate_id, ssl_forced, caching_enabled, block_exploits, advanced_config,
           meta, allow_websocket_upgrade, http2_support, forward_scheme, enabled, locations, hsts_enabled,
           hsts_subdomains, trust_forwarded_proto)
           values (datetime('now'), datetime('now'), 1, 0, ?, ?, ?, 0, 0, 0, 0, 1, ?, ?, 0, 0, 'http', 1, '[]', 0, 0, 0)""",
        (json.dumps([domain], separators=(",", ":")), upstream[0], upstream[1], advanced, meta))
    return cursor.lastrowid


def main():
    secret = GATEWAY.read_text(encoding="ascii").strip()
    assert 32 <= len(secret) <= 256 and all(c.isalnum() or c in "-_" for c in secret)
    keycloak = keycloak_upstream()
    backup = DB.with_name(DB.name + ".bak-ocr-oauth-" + datetime.now().strftime("%Y%m%d-%H%M%S"))
    shutil.copy2(DB, backup)
    plan = {AUTH: (keycloak, auth_locations(*keycloak)), MCP: (OCR_UPSTREAM, mcp_locations(*OCR_UPSTREAM, secret))}
    conn = sqlite3.connect(DB)
    written = {}
    with conn:
        for domain, (upstream, locations) in plan.items():
            host_id = upsert(conn, domain, upstream, locations)
            path = NGINX_DIR / f"{host_id}.conf"
            path.write_text(conf(host_id, domain, upstream, locations), encoding="utf-8")
            path.chmod(0o600)
            written[domain] = path.name
    conn.close()
    pod = subprocess.check_output(["k3s", "kubectl", "-n", "ix-nginxproxymanager", "get", "pod", "-l",
                                   "app.kubernetes.io/instance=nginxproxymanager", "-o",
                                   "jsonpath={.items[0].metadata.name}"], text=True).strip()
    test = subprocess.run(["k3s", "kubectl", "-n", "ix-nginxproxymanager", "exec", pod, "--", "nginx", "-t"],
                          capture_output=True, text=True)
    if test.returncode:
        raise SystemExit("nginx -t failed: " + test.stderr[-400:].replace(secret, "<redacted>"))
    subprocess.run(["k3s", "kubectl", "-n", "ix-nginxproxymanager", "exec", pod, "--", "nginx", "-s", "reload"],
                   check=True, capture_output=True)
    print(json.dumps({"backup": str(backup), "confs": written, "keycloak_upstream": f"{keycloak[0]}:{keycloak[1]}"}))


if __name__ == "__main__":
    main()
